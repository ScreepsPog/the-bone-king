TConstArrayView<FCrowdTuningEntry> GetCrowdTuningEntries()
{
	return TuningEntries;
}

float* FindCrowdTuningValue(FCrowdTuning& Tuning, const FString& Name)
{
	for (const FCrowdTuningEntry& Entry : TuningEntries)
	{
		if (Name.Equals(Entry.Name, ESearchCase::IgnoreCase))
		{
			return &(Tuning.*Entry.Member);
		}
	}
	return nullptr;
}
